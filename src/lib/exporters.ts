import * as XLSX from "xlsx";
import jsPDF from "jspdf";
import autoTable from "jspdf-autotable";

export type ReportSection = {
  title: string;
  columns: string[];
  rows: (string | number)[][];
  totals?: (string | number)[];
};

export type ReportDoc = {
  schoolName: string;
  schoolCode?: string | null;
  reportTitle: string;
  subtitle: string;
  sections: ReportSection[];
};

export function exportReportXlsx(doc: ReportDoc, filename: string) {
  const wb = XLSX.utils.book_new();
  for (const sec of doc.sections) {
    const aoa: (string | number)[][] = [
      [doc.schoolName],
      [doc.reportTitle],
      [doc.subtitle],
      [],
      [sec.title],
      sec.columns,
      ...sec.rows,
    ];
    if (sec.totals) aoa.push(sec.totals);
    const ws = XLSX.utils.aoa_to_sheet(aoa);
    ws["!cols"] = sec.columns.map((c, i) => ({
      wch: Math.max(c.length, ...sec.rows.map((r) => String(r[i] ?? "").length)) + 2,
    }));
    XLSX.utils.book_append_sheet(
      wb,
      ws,
      sec.title.slice(0, 28).replace(/[/\\?*[\]]/g, "-"),
    );
  }
  XLSX.writeFile(wb, filename);
}

export function exportReportPdf(doc: ReportDoc, filename: string) {
  const pdf = new jsPDF({ unit: "pt", format: "a4" });
  const pageW = pdf.internal.pageSize.getWidth();

  pdf.setFont("times", "bold").setFontSize(14);
  pdf.text(doc.schoolName, pageW / 2, 48, { align: "center" });
  pdf.setFont("times", "normal").setFontSize(10);
  if (doc.schoolCode) {
    pdf.text(`Registration ${doc.schoolCode}`, pageW / 2, 62, { align: "center" });
  }
  pdf.setFont("times", "bold").setFontSize(12);
  pdf.text(doc.reportTitle, pageW / 2, 84, { align: "center" });
  pdf.setFont("times", "italic").setFontSize(9);
  pdf.text(doc.subtitle, pageW / 2, 98, { align: "center" });

  let y = 118;
  for (const sec of doc.sections) {
    pdf.setFont("helvetica", "bold").setFontSize(10);
    pdf.text(sec.title, 40, y);
    y += 4;
    autoTable(pdf, {
      startY: y + 2,
      head: [sec.columns],
      body: sec.rows.map((r) => r.map((c) => (typeof c === "number" ? formatKes(c) : String(c)))),
      foot: sec.totals
        ? [sec.totals.map((c) => (typeof c === "number" ? formatKes(c) : String(c)))]
        : undefined,
      styles: { fontSize: 8.5, cellPadding: 4, font: "helvetica" },
      headStyles: { fillColor: [30, 86, 64], textColor: 255, fontStyle: "bold" },
      footStyles: { fillColor: [240, 235, 225], textColor: 20, fontStyle: "bold" },
      columnStyles: Object.fromEntries(
        sec.columns.map((_, i) => [
          i,
          { halign: i === 0 || (i === 1 && sec.columns.length > 3) ? "left" : "right" },
        ]),
      ),
      margin: { left: 40, right: 40 },
    });
    // @ts-expect-error jspdf autotable adds lastAutoTable
    y = pdf.lastAutoTable.finalY + 18;
    if (y > pdf.internal.pageSize.getHeight() - 100) {
      pdf.addPage();
      y = 48;
    }
  }

  const total = pdf.getNumberOfPages();
  for (let i = 1; i <= total; i++) {
    pdf.setPage(i);
    pdf.setFont("helvetica", "normal").setFontSize(8).setTextColor(120);
    pdf.text(
      `Generated by SomaFin · ${new Date().toLocaleString()}`,
      40,
      pdf.internal.pageSize.getHeight() - 24,
    );
    pdf.text(
      `Page ${i} of ${total}`,
      pageW - 40,
      pdf.internal.pageSize.getHeight() - 24,
      { align: "right" },
    );
  }

  pdf.save(filename);
}

function formatKes(n: number) {
  if (!n) return "—";
  const neg = n < 0;
  const abs = Math.abs(n);
  const fmt = new Intl.NumberFormat("en-KE", {
    minimumFractionDigits: 0,
    maximumFractionDigits: 0,
  }).format(abs);
  return neg ? `(${fmt})` : fmt;
}
